'use strict';

// Capacitor 以 http://localhost 加载打包在 APK 内的网页资源，Android 9+
// 默认禁止明文 HTTP，因此保留 usesCleartextTraffic。手机端对外只访问
// HTTPS 的 GitHub 快照与 Release，不再连接任何局域网数据服务。
// 幂等：重复运行不会重复插入。
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
const manifest = path.join(ROOT, 'android', 'app', 'src', 'main', 'AndroidManifest.xml');
if (!fs.existsSync(manifest)) {
  console.log('android/ 工程尚未创建，跳过 Android 补丁');
  process.exit(0);
}

// 1) 明文流量：Capacitor 以 http://localhost 加载 APK 内置网页
let xml = fs.readFileSync(manifest, 'utf8');
if (/android:usesCleartextTraffic/.test(xml)) {
  console.log('usesCleartextTraffic 已配置');
} else {
  if (!/<application\b/.test(xml)) {
    console.error('未找到 <application> 标签，请检查 AndroidManifest.xml');
    process.exit(1);
  }
  xml = xml.replace(/<application\b/, '<application\n        android:usesCleartextTraffic="true"');
  fs.writeFileSync(manifest, xml);
  console.log('已加入 android:usesCleartextTraffic="true"');
}

// 2) Cordova 插件工程的 gradle 变量文件
// capacitor-cordova-android-plugins/ 被 android/.gitignore 整体排除，不在版本控制内。
// cap sync 若被中途打断会先删后写，留下缺失的 cordova.variables.gradle 和被清空的
// PLUGIN GRADLE EXTENSIONS 区块，Gradle 会报 "Could not get unknown property
// 'cdvPluginPostBuildExtras'"。这里按 Capacitor 模板做幂等恢复，保证构建可自愈。
const pluginsDir = path.join(ROOT, 'android', 'capacitor-cordova-android-plugins');
if (fs.existsSync(pluginsDir)) {
  const varsFile = path.join(pluginsDir, 'cordova.variables.gradle');
  if (!fs.existsSync(varsFile)) {
    fs.writeFileSync(varsFile, [
      '// DO NOT EDIT THIS FILE! IT IS GENERATED EACH TIME "capacitor update" IS RUN',
      'ext {',
      "  cdvMinSdkVersion = project.hasProperty('minSdkVersion') ? rootProject.ext.minSdkVersion : 24",
      '  // Plugin gradle extensions can append to this to have code run at the end.',
      '  cdvPluginPostBuildExtras = []',
      '  cordovaConfig = [:]',
      '}',
      '',
    ].join('\n'));
    console.log('已恢复 capacitor-cordova-android-plugins/cordova.variables.gradle');
  }

  const pluginsGradle = path.join(pluginsDir, 'build.gradle');
  if (fs.existsSync(pluginsGradle)) {
    let gradle = fs.readFileSync(pluginsGradle, 'utf8');
    if (!/apply from:\s*["']cordova\.variables\.gradle["']/.test(gradle)) {
      const block = /\/\/ PLUGIN GRADLE EXTENSIONS START[\s\S]*?\/\/ PLUGIN GRADLE EXTENSIONS END/;
      if (block.test(gradle)) {
        gradle = gradle.replace(
          /(\/\/ PLUGIN GRADLE EXTENSIONS START)[\s\S]*?(\/\/ PLUGIN GRADLE EXTENSIONS END)/,
          '$1\napply from: "cordova.variables.gradle"\n$2'
        );
      } else {
        gradle += '\napply from: "cordova.variables.gradle"\n';
      }
      fs.writeFileSync(pluginsGradle, gradle);
      console.log('已恢复插件工程的 apply from: "cordova.variables.gradle"');
    }
  }
}
