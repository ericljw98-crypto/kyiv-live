function officialStreet(query) {
  const s = String(query ?? '').trim();
  if (!s) return s;
  if (HAS_CYR.test(s)) return s;
  for (const [zh, uk] of STREET_QUERY_ALIASES) {
    if (s === zh || s.includes(zh)) return uk;
  }
  // 纯拉丁转写按官方原名兜底，避免把中文送去官方库得到空结果。
  if (/d obrov|dobrov|panfil/i.test(s)) {
    return /panfil/i.test(s) ? 'Панфіловців' : 'Добровольчих батальйонів';
  }
  return s;
}

