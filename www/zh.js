/** 从乌克兰语正文抽取中文要点。返回纯中文，最多 maxLen 字。 */
function summarize(text, maxLen = 180) {
  const s = cleanText(text);
  if (!s) return '';
  const lower = s.toLowerCase();
  const points = [];
  for (const [re, zhText] of SUMMARY_RULES) {
    if (re.test(lower) && !points.includes(zhText)) points.push(zhText);
    if (points.length >= 3) break;
  }
  const scopeHits = SUMMARY_SCOPES.filter(([re]) => re.test(lower)).map(([, v]) => v);
  const broad = scopeHits.filter((v) => v === '全市各区' || v === '基辅市');
  const banks = scopeHits.filter((v) => v === '左岸' || v === '右岸');
  let scope = '';
  if (banks.length) scope = `基辅${banks.join('与')}地区`;
  else if (broad.includes('全市各区')) scope = '基辅全市各区';
  else if (broad.length) scope = '基辅市';
  const street = STREET_NAMES.find(([uk]) => lower.includes(uk.toLowerCase()));
  const bits = [];
  if (points.length) bits.push(points.join('，'));
  if (street) bits.push(`涉及 ${street[1]}`);
  if (scope) bits.push(`范围${scope}`);
  if (!bits.length) {
    const t = translateTitle(s.slice(0, 110));
    bits.push(t);
  }
  const date = s.match(/\b(\d{1,2}\.\d{1,2}\.\d{4})(?:\s+(\d{1,2}:\d{2}))?/);
  if (date) bits.push(`发布于 ${date[1]}${date[2] ? ` ${date[2]}` : ''}`);
  let out = `要点：${bits.join('；')}。`;
  if (maxLen && out.length > maxLen) out = `${out.slice(0, maxLen)}…`;
  return out;
}

