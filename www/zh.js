/** 把地址库返回的街道名／片区名转成中文；未收录的走通用翻译。 */
function zhStreet(name) {
  const s = cleanText(name);
  if (!s) return '';
  const lower = s.toLowerCase();
  for (const [uk, zh] of STREET_NAMES) {
    if (lower.includes(uk.toLowerCase())) return zh;
  }
  const out = toChinese(s);
  return /[街道路巷区片]$/.test(out) ? out : `${out}街`;
}

